/// AppShell 的「主舞台」枚举。
///
/// ## 为什么单独一个文件
/// 页面需要回调「切到某个舞台」，而 Shell 需要 import 各个页面 ——
/// 枚举放这里就能同时被两边引用，不会形成别扭的循环依赖。
enum ShellStage {
  /// 首页（四张快捷卡 + 最近播放）。
  home,

  /// 音乐库（完整曲库，分页）。
  library,

  /// 按歌手分组。
  artists,

  /// 按专辑分组。
  albums,

  /// 按风格标签分组。
  genres,

  /// 收藏（V4 起是**本机收藏集合**；服务端只有只读的 `isFavorite`，
  /// 没有写接口，首次进入时播种一次，之后只认本机那一份）。
  favorites,

  /// 最近播放（本机收听历史，按实际播放时间倒序）。
  recent,

  /// 按添加时间倒序。
  recentAdded,

  /// 搜索。
  search,
}
